"""Writes tests/Fixtures/AIParity.luau: 300 seeded matches between two "adaptive" readers
(sim/balance.py make_reader), the policy the Guardian Trials use. tests/Specs/BattleAI.spec.luau
plays the same matches with Server/Battle/BattleAI and must reproduce each one exactly."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import engine as E
import balance as B
from parity import deck_for

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = 300


def play(seed):
    a, b = deck_for(seed)
    m = E.Match(a, b, seed)
    g = E.PRNG(seed * 7 + 3)
    pa, pb = B.make_reader(), B.make_reader()
    while m.outcome() is None:
        x, y = pa(m, 0, g), pb(m, 1, g)
        m.resolve(x, y)
        for i in (0, 1):
            if m.needs_next(i):
                m.choose_next(i, m.default_next(i))
    return m


if __name__ == "__main__":
    rows = []
    for seed in range(1, N + 1):
        m = play(seed)
        rows.append(f"{{{m.outcome()},{m.round},{E.signature(m)}}}")
    lines = ["--!strict", "-- Generated by sim/ai_parity.py. Do not edit.",
             "-- Row n = seed n: { winner, rounds, event signature } for reader vs reader.",
             "return {"]
    for i in range(0, N, 10):
        lines.append("\t" + ",".join(rows[i:i + 10]) + ",")
    lines.append("}")
    open(os.path.join(ROOT, "tests", "Fixtures", "AIParity.luau"), "w").write("\n".join(lines) + "\n")
    print(f"wrote {N} reader-vs-reader matches")
