"""Writes tests/Fixtures/BattleParity.luau: 1,000 seeded matches played by the reference engine.
The Luau spec (tests/Specs/BattleParity.spec.luau) builds the same decks and picks from the same
seeds and must reproduce each match's winner, length and event signature exactly."""
import os, engine as E

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IDS = [c["id"] for c in E.C["characters"]]
N = 1000


def deck_for(seed):
    g = E.PRNG(seed * 3 + 1)
    def one():
        pool = list(IDS)
        out = []
        for _ in range(3):
            i = int(g.next() * len(pool))
            out.append((pool.pop(i), 1 + int(g.next() * 15)))
        return out
    return one(), one()


if __name__ == "__main__":
    rows = []
    for seed in range(1, N + 1):
        a, b = deck_for(seed)
        m = E.play(a, b, seed)
        rows.append(f"{{{m.outcome()},{m.round},{E.signature(m)}}}")
    sample = E.play(*deck_for(1), 1)
    lines = ["--!strict", "-- Generated by sim/parity.py from sim/engine.py. Do not edit.",
             "-- Row n = seed n: { winner, rounds, event signature }.",
             "return {", "\tmatches = {"]
    for i in range(0, N, 10):
        lines.append("\t\t" + ",".join(rows[i:i + 10]) + ",")
    lines.append("\t},")
    lines.append("\t-- Full event log of seed 1, for debugging a mismatch.")
    lines.append("\tseed1 = {")
    for e in sample.events:
        lines.append(f'\t\t"{e}",')
    lines.append("\t},")
    lines.append("}")
    os.makedirs(os.path.join(ROOT, "tests", "Fixtures"), exist_ok=True)
    open(os.path.join(ROOT, "tests", "Fixtures", "BattleParity.luau"), "w").write("\n".join(lines) + "\n")
    wins = sum(1 for r in rows if r.startswith("{1"))
    print(f"wrote {N} matches; side 1 won {wins}")
