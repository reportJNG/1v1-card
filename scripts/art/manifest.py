"""The step-5 asset manifest (CARDS_EGGS_MISSION section 3).

  python scripts/art/manifest.py            rescan art/ui/kit, write art/ui/MANIFEST_V2.json and
                                            src/shared/Config/CardKit.luau
  python scripts/art/manifest.py pending    list kit files without an uploaded id (for upload)
  python scripts/art/manifest.py ids <json> merge {"<url or file>": "rbxassetid://..."} results
                                            from the Studio MCP upload_image into art/ui/kit/ids.json

Every kit image gets: slot, file, size, 9-slice margins (if any), route (B = Blender render,
C = code, O = owner image), status (TEMP or FINAL) and its Roblox asset id. An id is tied to the
file's content hash, so a re-rendered file shows up as pending again.
"""
import hashlib
import json
import os
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
KIT = os.path.join(ROOT, "art", "ui", "kit")
IDS = os.path.join(KIT, "ids.json")
OUT = os.path.join(ROOT, "art", "ui", "MANIFEST_V2.json")
LUAU = os.path.join(ROOT, "src", "shared", "Config", "CardKit.luau")

# Route by slot prefix; Blender renders are finished in 2D (glow) but stay route B.
ROUTE_B = ("emblem_", "egg_", "pedestal_", "shard_", "crown_")
SLICE = {
    # slot prefix: (x0, y0, x1, y1) in image px
    "bar_level_bg": (24, 0, 232, 32),
    "bar_level_fill": (24, 0, 232, 32),
    "bar_level_glow": (40, 0, 216, 64),
    "toast_rarity_": (64, 40, 448, 88),
    "odds_row_": (40, 20, 472, 44),
    "filter_chip_": (40, 24, 152, 40),
    "empty_slot": (60, 60, 196, 292),
}


def sha(path):
    return hashlib.sha1(open(path, "rb").read()).hexdigest()[:16]


def load_ids():
    return json.load(open(IDS)) if os.path.exists(IDS) else {}


def scan():
    ids = load_ids()
    entries = []
    for f in sorted(os.listdir(KIT)):
        if not f.endswith(".png"):
            continue
        slot = f[:-4]
        path = os.path.join(KIT, f)
        w, h = Image.open(path).size
        rec = ids.get(slot)
        cur = rec if rec and rec.get("sha") == sha(path) else None
        sl = next((v for k, v in SLICE.items() if slot.startswith(k)), None)
        entries.append({
            "slot": slot,
            "file": f"art/ui/kit/{f}",
            "size": [w, h],
            "slice": list(sl) if sl else None,
            "route": "B" if slot.startswith(ROUTE_B) else "C",
            "status": "FINAL" if cur else "TEMP",
            "id": cur["id"] if cur else None,
        })
    return entries


def write():
    entries = scan()
    geo = json.load(open(os.path.join(KIT, "geometry.json")))
    json.dump({"note": "Generated by scripts/art/manifest.py. FINAL = produced by this mission's "
               "pipeline and uploaded; the owner may still replace any slot with route O art.",
               "geometry": geo, "assets": entries}, open(OUT, "w"), indent=1)
    lines = [
        "--!strict",
        "-- Generated by scripts/art/manifest.py from art/ui/MANIFEST_V2.json. Do not edit by hand.",
        "-- The step-5 card and egg kit (CARDS_EGGS_MISSION): every image slot with its uploaded id,",
        "-- size and 9-slice centre, plus the card geometry shared by every frame layer (fractions of",
        "-- the canvas: card = the 5:7 card inside the bleed, window = the art window).",
        "",
        "export type Slot = { id: string, size: { number }, slice: { number }?, route: string }",
        "export type Rect = { number }",
        "",
        "local Slots: { [string]: Slot } = {",
    ]
    for e in entries:
        if not e["id"]:
            continue
        sl = f"{{ {', '.join(map(str, e['slice']))} }}" if e["slice"] else "nil"
        lines.append(f'\t{e["slot"]} = {{ id = "{e["id"]}", size = {{ {e["size"][0]}, {e["size"][1]} }}, '
                     f'slice = {sl}, route = "{e["route"]}" }},')
    lines += ["}", "", "local Geometry: { [string]: { canvas: { number }, card: Rect, window: Rect } } = {"]
    for k, g in geo.items():
        lines.append(f"\t{k} = {{ canvas = {{ {g['canvas'][0]}, {g['canvas'][1]} }}, "
                     f"card = {{ {', '.join(map(str, g['card']))} }}, window = {{ {', '.join(map(str, g['window']))} }} }},")
    lines += ["}", "", "return table.freeze({ Slots = table.freeze(Slots), Geometry = table.freeze(Geometry) })", ""]
    open(LUAU, "w", encoding="utf-8").write("\n".join(lines))
    pend = [e["slot"] for e in entries if not e["id"]]
    print(f"{len(entries)} kit images, {len(entries) - len(pend)} uploaded, {len(pend)} pending")


def merge_ids(result_json):
    res = json.loads(open(result_json).read()) if os.path.exists(result_json) else json.loads(result_json)
    ids = load_ids()
    for key, aid in res.items():
        slot = os.path.basename(key)[:-4]
        path = os.path.join(KIT, slot + ".png")
        if os.path.exists(path) and str(aid).startswith("rbxassetid://"):
            ids[slot] = {"id": aid, "sha": sha(path)}
    json.dump(ids, open(IDS, "w"), indent=1, sort_keys=True)
    print("merged", len(res))


if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] == "pending":
        print("\n".join(e["file"] for e in scan() if not e["id"]))
    elif a and a[0] == "ids":
        merge_ids(a[1])
        write()
    else:
        write()
